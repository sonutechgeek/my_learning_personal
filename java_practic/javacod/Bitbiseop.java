class Bitbiseop {
    public static void main(String[] args) {
        int x = 8, y = 9;
        System.out.println("BITBISE AND OPERATER");
        System.out.println(x & y);

        System.out.println("BITBISE OR OPERATER");
        System.out.println(x | y);

        System.out.println("BITBISE XOR OPERATER");
        System.out.println(x ^ y);

        System.out.println("BITBISE NOT OPERATER");
        System.out.println(~x);

        System.out.println("BITBISE LEFT SHIF T OPERATER");
        System.out.println(y << 2);

        System.out.println("BITBISE RIGHT SHIFT OPERATER");
        System.out.println(x >> 2);
    }
}